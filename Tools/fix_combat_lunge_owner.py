"""Expand the existing swept advance notify from BP_Player to BaseCharacter."""
import unreal
b=unreal.load_asset('/Game/Gameplay/Notify/ANS/ANS_AttackLungeWindow')
g=unreal.find_object(None,b.get_path_name()+':Received_NotifyTick')
ed=unreal.BlueprintGraphEditor.get_graph_editor(g)
def load(name):return unreal.find_object(None,g.get_path_name()+'.'+name)
def pin(n,name):return next(p for p in n.list_all_pins() if str(p.get_pin_name())==name)
def link(a,an,b,bn):assert pin(a,an).try_create_connection(pin(b,bn))
old=next(n for n in ed.list_all_nodes() if isinstance(n,unreal.K2Node_DynamicCast))
ed.remove_nodes([old])
typ=next(t for t in ed.list_available_nodes([]) if t.endswith('|CastToBaseCharacter'))
cast=ed.create_node_from_name(typ,unreal.Vector2D(300,0),[])
result=next(str(p.get_pin_name()) for p in cast.list_all_pins() if str(p.get_pin_name()).startswith('As'))
link(load('K2Node_FunctionEntry_0'),'then',cast,'execute')
link(load('K2Node_CallFunction_0'),'ReturnValue',cast,'Object')
link(cast,'then',load('K2Node_CallFunction_2'),'execute')
link(cast,result,load('K2Node_CallFunction_1'),'self')
link(cast,result,load('K2Node_CallFunction_2'),'self')
link(cast,'CastFailed',load('K2Node_FunctionResult_0'),'execute')
ed.add_comment_node('Shared swept advance for player and enemy. Speed and window remain per montage; owner is validated as BaseCharacter.',unreal.Vector2D(0,-220),unreal.Vector2D(1200,150))
unreal.BlueprintEditorLibrary.compile_blueprint(b)
assert not ed.list_nodes_with_errors()
assert unreal.EditorAssetLibrary.save_loaded_asset(b,False)
print('Shared lunge owner saved')
